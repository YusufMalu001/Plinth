import { fetchApi } from '../api/client';
import type {
  JobWorkOrderDto,
  JobWorkMaterialIssueDto,
  JobWorkCustodyLedgerDto,
  JobWorkReceiptReturnDto,
  JobWorkReconciliationDto,
  VendorCustodyBalanceDto,
  JobWorkAnalyticsDto,
  JobWorkOrderStatus,
  JobWorkReturnDisposition
} from '@synergy/types';

export interface JobWorkOrderQueryFilters {
  vendorId?: string;
  status?: JobWorkOrderStatus;
  productId?: string;
  materialId?: string;
  search?: string;
  page?: number;
  limit?: number;
}

export interface CreateJobWorkOrderPayload {
  orderNumber?: string;
  vendorId: string;
  purchaseOrderId?: string | null;
  productId?: string | null;
  targetQuantity?: number;
  targetUomId?: string | null;
  rawMaterialInputQty?: number;
  expectedScrapRate?: number;
  deliveryLocationId?: string | null;
  natureOfProcessing?: string | null;
  specifications?: string | null;
  notes?: string | null;
  evidenceAttachments?: Array<{ name: string; url: string; size?: number; type?: string }> | null;
  lines: Array<{
    materialId?: string | null;
    productId?: string | null;
    uomId: string;
    requiredQuantity: number;
    allocatedQuantity?: number;
    notes?: string | null;
  }>;
}

export interface IssueJobWorkMaterialPayload {
  challanNumber?: string;
  jobWorkOrderId?: string | null;
  vendorId: string;
  dispatchLocationId: string;
  materialId?: string | null;
  productId?: string | null;
  uomId: string;
  quantity: number;
  vehicleNumber?: string | null;
  transporterName?: string | null;
  driverContact?: string | null;
  notes?: string | null;
}

export interface ReceiveJobWorkReturnPayload {
  returnNumber?: string;
  jobWorkOrderId?: string | null;
  vendorId: string;
  locationId: string;
  disposition?: JobWorkReturnDisposition;
  productId?: string | null;
  materialId?: string | null;
  uomId: string;
  expectedQuantity: number;
  receivedQuantity: number;
  acceptedQuantity: number;
  scrapQuantity?: number;
  consumedRawMaterial?: number;
  notes?: string | null;
  generateDebitNoteForShortage?: boolean;
  debitNoteReason?: string;
}

export interface CreateJobWorkReconciliationPayload {
  jobWorkOrderId: string;
  returnId?: string | null;
  reason?: string | null;
  financialImpactNotes?: string | null;
  evidenceAttachments?: Array<{ name: string; url: string; size?: number; type?: string }> | null;
  autoGenerateDebitNote?: boolean;
}

export const jobWorkApi = {
  // Analytics
  getAnalytics: async (): Promise<JobWorkAnalyticsDto> => {
    return fetchApi<JobWorkAnalyticsDto>('/job-work/analytics');
  },

  getVendorScoring: async (vendorId?: string) => {
    const query = new URLSearchParams();
    if (vendorId) query.set('vendorId', vendorId);
    const qs = query.toString();
    return fetchApi<any>(`/job-work/analytics/scoring${qs ? `?${qs}` : ''}`);
  },

  // Balances & Custody Ledger
  getVendorCustodyBalances: async (vendorId?: string): Promise<VendorCustodyBalanceDto[]> => {
    const query = new URLSearchParams();
    if (vendorId) query.set('vendorId', vendorId);
    const qs = query.toString();
    return fetchApi<VendorCustodyBalanceDto[]>(
      `/job-work/custody/balances${qs ? `?${qs}` : ''}`
    );
  },

  getCustodyLedger: async (filters?: {
    vendorId?: string;
    jobWorkOrderId?: string;
    materialId?: string;
    productId?: string;
    page?: number;
    limit?: number;
  }): Promise<{ items: JobWorkCustodyLedgerDto[]; total: number; page: number; limit: number }> => {
    const query = new URLSearchParams();
    if (filters?.vendorId) query.set('vendorId', filters.vendorId);
    if (filters?.jobWorkOrderId) query.set('jobWorkOrderId', filters.jobWorkOrderId);
    if (filters?.materialId) query.set('materialId', filters.materialId);
    if (filters?.productId) query.set('productId', filters.productId);
    if (filters?.page) query.set('page', String(filters.page));
    if (filters?.limit) query.set('limit', String(filters.limit));
    const qs = query.toString();
    return fetchApi<{ items: JobWorkCustodyLedgerDto[]; total: number; page: number; limit: number }>(
      `/job-work/custody/ledger${qs ? `?${qs}` : ''}`
    );
  },
  // Orders
  getOrders: async (
    filters?: JobWorkOrderQueryFilters
  ): Promise<{ items: JobWorkOrderDto[]; total: number; page: number; limit: number }> => {
    const query = new URLSearchParams();
    if (filters?.vendorId) query.set('vendorId', filters.vendorId);
    if (filters?.status) query.set('status', filters.status);
    if (filters?.productId) query.set('productId', filters.productId);
    if (filters?.materialId) query.set('materialId', filters.materialId);
    if (filters?.search) query.set('search', filters.search);
    if (filters?.page) query.set('page', String(filters.page));
    if (filters?.limit) query.set('limit', String(filters.limit));
    const qs = query.toString();
    return fetchApi<{ items: JobWorkOrderDto[]; total: number; page: number; limit: number }>(
      `/job-work/orders${qs ? `?${qs}` : ''}`
    );
  },
  getOrderById: async (id: string): Promise<JobWorkOrderDto> => {
    return fetchApi<JobWorkOrderDto>(`/job-work/orders/${id}`);
  },
  createOrder: async (payload: CreateJobWorkOrderPayload): Promise<JobWorkOrderDto> => {
    return fetchApi<JobWorkOrderDto>('/job-work/orders', {
      method: 'POST',
      body: JSON.stringify(payload)
    });
  },
  approveOrder: async (id: string, remarks?: string): Promise<JobWorkOrderDto> => {
    return fetchApi<JobWorkOrderDto>(`/job-work/orders/${id}/approve`, {
      method: 'POST',
      body: JSON.stringify({ remarks })
    });
  },

  closeOrder: async (id: string, remarks?: string): Promise<JobWorkOrderDto> => {
    return fetchApi<JobWorkOrderDto>(`/job-work/orders/${id}/close`, {
      method: 'POST',
      body: JSON.stringify({ remarks })
    });
  },
  // Delivery Challans / Material Issues
  issueMaterial: async (payload: IssueJobWorkMaterialPayload): Promise<JobWorkMaterialIssueDto> => {
    return fetchApi<JobWorkMaterialIssueDto>('/job-work/challans', {
      method: 'POST',
      body: JSON.stringify(payload)
    });
  },
  getChallans: async (filters?: {
    vendorId?: string;
    jobWorkOrderId?: string;
    page?: number;
    limit?: number;
  }): Promise<{ items: JobWorkMaterialIssueDto[]; total: number; page: number; limit: number }> => {
    const query = new URLSearchParams();
    if (filters?.vendorId) query.set('vendorId', filters.vendorId);
    if (filters?.jobWorkOrderId) query.set('jobWorkOrderId', filters.jobWorkOrderId);
    if (filters?.page) query.set('page', String(filters.page));
    if (filters?.limit) query.set('limit', String(filters.limit));
    const qs = query.toString();
    return fetchApi<{ items: JobWorkMaterialIssueDto[]; total: number; page: number; limit: number }>(
      `/job-work/challans${qs ? `?${qs}` : ''}`
    );
  },
  // Returns / GRN
  receiveReturn: async (
    payload: ReceiveJobWorkReturnPayload
  ): Promise<{ receiptReturn: JobWorkReceiptReturnDto; grn: unknown; debitNote: unknown }> => {
    return fetchApi<{ receiptReturn: JobWorkReceiptReturnDto; grn: unknown; debitNote: unknown }>(
      '/job-work/returns',
      {
        method: 'POST',
        body: JSON.stringify(payload)
      }
    );
  },
  getReturns: async (filters?: {
    vendorId?: string;
    jobWorkOrderId?: string;
    page?: number;
    limit?: number;
  }): Promise<{ items: JobWorkReceiptReturnDto[]; total: number; page: number; limit: number }> => {
    const query = new URLSearchParams();
    if (filters?.vendorId) query.set('vendorId', filters.vendorId);
    if (filters?.jobWorkOrderId) query.set('jobWorkOrderId', filters.jobWorkOrderId);
    if (filters?.page) query.set('page', String(filters.page));
    if (filters?.limit) query.set('limit', String(filters.limit));
    const qs = query.toString();
    return fetchApi<{ items: JobWorkReceiptReturnDto[]; total: number; page: number; limit: number }>(
      `/job-work/returns${qs ? `?${qs}` : ''}`
    );
  },
  // Reconciliation
  reconcileOrder: async (payload: CreateJobWorkReconciliationPayload): Promise<JobWorkReconciliationDto> => {
    return fetchApi<JobWorkReconciliationDto>('/job-work/reconciliations', {
      method: 'POST',
      body: JSON.stringify(payload)
    });
  },
  getReconciliations: async (filters?: {
    jobWorkOrderId?: string;
    status?: string;
    page?: number;
    limit?: number;
  }): Promise<{ items: JobWorkReconciliationDto[]; total: number; page: number; limit: number }> => {
    const query = new URLSearchParams();
    if (filters?.jobWorkOrderId) query.set('jobWorkOrderId', filters.jobWorkOrderId);
    if (filters?.status) query.set('status', filters.status);
    if (filters?.page) query.set('page', String(filters.page));
    if (filters?.limit) query.set('limit', String(filters.limit));
    const qs = query.toString();
    return fetchApi<{ items: JobWorkReconciliationDto[]; total: number; page: number; limit: number }>(
      `/job-work/reconciliations${qs ? `?${qs}` : ''}`
    );
  }
};
