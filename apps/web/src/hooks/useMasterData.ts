function isGeneratedVariantCode(parentCode: string | undefined, variantCode: string): boolean {
  if (!parentCode) return false;
  const prefix = `${parentCode}-VAR-`.toUpperCase();
  const normalizedCode = variantCode.toUpperCase();
  return normalizedCode.startsWith(prefix) && /^\d+$/.test(normalizedCode.slice(prefix.length));
}

export function extractProductVariants(product: Product): Product[] {
  if (product.isVariant || (product.metadata as any)?.isVariant) {
    return [];
  }

  interface ProductVariantDraft {
    id?: string;
    productRecordId?: string;
    sku?: string;
    name?: string;
    variantLabel?: string;
    measurementValue?: string;
    uomId?: string;
    openingStock?: number | string;
    minStockLevel?: number | string;
    reorderPoint?: number | string;
    standardPrice?: number | string;
    customFields?: any[];
  }

  const drafts: ProductVariantDraft[] = [];

  const addOrMergeDraft = (v: any, preferSku = false) => {
    if (!v || typeof v !== 'object') return;

    const sku = ((v.sku || v.code || '') as string).trim();
    const id = ((v.id || '') as string).trim();
    const productRecordId = ((v.productRecordId || (v.metadata as any)?.productRecordId || '') as string).trim();
    const name = ((v.name || '') as string).trim();
    const nameLabel = getVariantLabel(product.name, name);
    const storedVariantLabel = String(v.variantLabel || (v.metadata as any)?.variantLabel || '').trim();
    const variantLabel = name && name.toLowerCase() !== product.name.toLowerCase()
      ? nameLabel
      : storedVariantLabel || nameLabel;
    const rawVal = ((v.measurementValue || v.size || (v.specifications as any)?.measurementValue || '') as string).trim();
    const uomId = v.uomId || (v.specifications as any)?.uomId;
    const openingStock = v.openingStock !== undefined ? v.openingStock : (v.specifications as any)?.openingStock;
    const minStockLevel = v.minStockLevel !== undefined ? v.minStockLevel : (v.specifications as any)?.minStockLevel;
    const reorderPoint = v.reorderPoint !== undefined ? v.reorderPoint : (v.specifications as any)?.reorderPoint;
    const standardPrice = v.price !== undefined ? v.price : (v.standardPrice !== undefined ? v.standardPrice : (v.specifications as any)?.standardPrice);
    const customFields = v.customFields || (v.specifications as any)?.customFields;

    const matchIndex = drafts.findIndex((d) => {
      // A matching record ID is definitive, but SKU alone is not: legacy
      // variants can share a generated SKU while representing LHS and RHS.
      if (id && d.id && !id.startsWith('temp-') && !id.startsWith('var-') && !d.id.startsWith('temp-') && !d.id.startsWith('var-') && id === d.id) return true;

      const normalizedName = getVariantLabel(product.name, variantLabel || name, rawVal).toLowerCase();
      const normalizedDraftName = getVariantLabel(product.name, d.variantLabel || d.name, d.measurementValue).toLowerCase();
      const sameName = !normalizedName || !normalizedDraftName || normalizedName === normalizedDraftName;
      const sameMeasurement = !rawVal || !d.measurementValue || rawVal.toLowerCase() === d.measurementValue.toLowerCase();

      // Merge records only when their option identity agrees. This prevents a
      // shared SKU or measurement from turning distinct variants into one row.
      if (normalizedName && normalizedDraftName && normalizedName === normalizedDraftName && sameMeasurement) return true;
      if (sameName && sameMeasurement && sku && d.sku && sku.toUpperCase() === d.sku.toUpperCase()) return true;
      if (sameName && rawVal && d.measurementValue && rawVal.toLowerCase() === d.measurementValue.toLowerCase()) return true;

      return false;
    });

    if (matchIndex >= 0) {
      const target = drafts[matchIndex];
      if (productRecordId) target.productRecordId = productRecordId;
      // Prefer real permanent database ID over temporary/client-generated ID
      if (id && (!target.id || target.id.startsWith('temp-') || target.id.startsWith('var-'))) {
        target.id = id;
      }
      if (preferSku && ('sku' in v || 'code' in v)) target.sku = sku;
      else if (!target.sku && sku) target.sku = sku;
      if (!target.name && name) target.name = name;
      if (!target.variantLabel && variantLabel) target.variantLabel = variantLabel;
      if (!target.measurementValue && rawVal) target.measurementValue = rawVal;
      if (!target.uomId && uomId) target.uomId = uomId;
      if (target.openingStock === undefined && openingStock !== undefined) target.openingStock = openingStock;
      if (target.minStockLevel === undefined && minStockLevel !== undefined) target.minStockLevel = minStockLevel;
      if (target.reorderPoint === undefined && reorderPoint !== undefined) target.reorderPoint = reorderPoint;
      if (target.standardPrice === undefined && standardPrice !== undefined) target.standardPrice = standardPrice;
      if (!target.customFields && customFields) target.customFields = customFields;
    } else {
      drafts.push({
        id: id || undefined,
        productRecordId: productRecordId || undefined,
        sku: sku || undefined,
        name: name || undefined,
        variantLabel: variantLabel || undefined,
        measurementValue: rawVal || undefined,
        uomId: uomId || undefined,
        openingStock,
        minStockLevel,
        reorderPoint,
        standardPrice,
        customFields,
      });
    }
  };

  // 1. Process Prisma variants when no configured metadata list exists. When
  // metadata has options, it is the parent's saved configuration; stale rows
  // left in product_variants must not leak back into selectors.
  const productMetadata = (product.metadata || {}) as any;
  const configuredVariants = [productMetadata.measurementVariants, productMetadata.variants]
    .some((variants) => Array.isArray(variants) && variants.length > 0);
  if (!configuredVariants && Array.isArray((product as any).variants)) {
    for (const v of (product as any).variants) {
      if (v.status === 'INACTIVE') continue;
      addOrMergeDraft(v);
    }
  }

  // 2. Process metadata.measurementVariants
  if (Array.isArray(product.metadata?.measurementVariants)) {
    for (const v of product.metadata.measurementVariants) {
      addOrMergeDraft(v, true);
    }
  }

  // 3. Process metadata.variants
  if (Array.isArray(product.metadata?.variants)) {
    for (const v of product.metadata.variants) {
      addOrMergeDraft(v, true);
    }
  }

  return drafts.map((v, idx) => {
    const rawVal = (v.measurementValue || '').trim();
    const storedName = (v.name || '').trim();
    const storedSku = (v.sku || (v as any).code || '').trim();
    const vSku = isGeneratedVariantCode(product.sku, storedSku) ? '' : storedSku;

    const isGenericVariantName = !storedName || /^variant\s*\d*$/i.test(storedName) || /^\d+$/.test(storedName);
    const displayName = getVariantLabel(product.name, isGenericVariantName ? '' : (storedName && storedName.toLowerCase() !== product.name.toLowerCase() ? storedName : v.variantLabel || storedName), rawVal || `Variant ${idx + 1}`);

    const vId = v.id && !v.id.startsWith('temp-') && !v.id.startsWith('var-')
      ? v.id
      : `${product.id}__var__${vSku || idx + 1}`;

    const numOpeningStock = Number(v.openingStock) || 0;
    const numPrice = Number(v.standardPrice ?? (product as any).sellingPrice ?? 0) || 0;
    const numMinStock = Number(v.minStockLevel ?? (product as any).minStockLevel ?? 0) || 0;
    const numReorder = Number(v.reorderPoint ?? (product as any).reorderPoint ?? 0) || 0;

    const variantProduct: Product = {
      ...product,
      id: vId,
      sku: vSku,
      name: displayName,
      description: product.description
        ? `${product.description}${rawVal ? ` · Specification: ${rawVal}` : ''}`
        : (rawVal ? `Variant measurement: ${rawVal}` : undefined),
      isVariant: true,
      parentProductId: product.id,
      parentProductName: product.name,
      parentSku: product.sku,
      parentOptionId: product.id,
      parentItemName: product.name,
      measurementValue: rawVal || undefined,
      openingStock: numOpeningStock,
      standardPrice: numPrice,
      minStockLevel: numMinStock,
      reorderPoint: numReorder,
      uomId: v.uomId || product.uomId,
      uom: product.uom,
      category: product.category,
      categoryId: product.categoryId,
      productFamily: product.productFamily,
      productFamilyId: product.productFamilyId,
      status: product.status || 'ACTIVE',
      metadata: {
        ...(product.metadata || {}),
        isVariant: true,
        productRecordId: v.productRecordId,
        parentProductId: product.id,
        measurementValue: rawVal,
        openingStock: numOpeningStock,
        standardPrice: numPrice,
      },
    };
    return variantProduct;
  });
}

export function expandProductsWithVariants(products: Product[]): Product[] {
  const result: Product[] = [];
  const seenIds = new Set<string>();
  const parentIds = new Set(products.filter((product) =>
    !product.isVariant && !(product.metadata as any)?.isVariant && !product.parentProductId
  ).map((product) => product.id));

  for (const product of products) {
    const parentId = product.parentProductId || (product.metadata as any)?.parentProductId;
    // The parent's configured variants are authoritative. A separate variant
    // product record may have a different ID for the same option.
    if (parentId && parentIds.has(parentId)) continue;
    if (!seenIds.has(product.id)) {
      seenIds.add(product.id);
      result.push(product);
    }
    if (!product.isVariant && !(product.metadata as any)?.isVariant) {
      const variants = extractProductVariants(product);
      for (const variant of variants) {
        if (!seenIds.has(variant.id)) {
          seenIds.add(variant.id);
          result.push(variant);
        }
      }
    }
  }
  return result;
}

export function extractMaterialVariants(material: Material): Material[] {
  if (material.isVariant || (material.specs as any)?.isVariant) {
    return [];
  }

  interface MaterialVariantDraft {
    id?: string;
    code?: string;
    sku?: string;
    name?: string;
    measurementValue?: string;
    uomId?: string;
    openingStock?: number | string;
    minStockLevel?: number | string;
    reorderPoint?: number | string;
    standardCost?: number | string;
    customFields?: any[];
  }

  const drafts: MaterialVariantDraft[] = [];

  const addOrMergeDraft = (v: any, preferCode = false) => {
    if (!v || typeof v !== 'object') return;

    const code = ((v.code || v.sku || '') as string).trim();
    const id = ((v.id || '') as string).trim();
    const name = ((v.name || '') as string).trim();
    const rawVal = ((v.measurementValue || v.size || (v.specifications as any)?.measurementValue || '') as string).trim();
    const uomId = v.uomId || (v.specifications as any)?.uomId;
    const openingStock = v.openingStock !== undefined ? v.openingStock : (v.specifications as any)?.openingStock;
    const minStockLevel = v.minStockLevel !== undefined ? v.minStockLevel : (v.specifications as any)?.minStockLevel;
    const reorderPoint = v.reorderPoint !== undefined ? v.reorderPoint : (v.specifications as any)?.reorderPoint;
    const standardCost = v.standardCost !== undefined ? v.standardCost : (v.standardPrice !== undefined ? v.standardPrice : (v.specifications as any)?.standardPrice);
    const customFields = v.customFields || (v.specifications as any)?.customFields;

    const matchIndex = drafts.findIndex((d) => {
      const dCode = d.code || d.sku || '';
      // 1. Direct code/sku match
      if (code && dCode && code.toUpperCase() === dCode.toUpperCase()) return true;

      // 2. Direct database ID match (for permanent IDs)
      if (id && d.id && !id.startsWith('temp-') && !id.startsWith('var-') && !d.id.startsWith('temp-') && !d.id.startsWith('var-') && id === d.id) return true;

      // 3. Name & measurement value matching
      if (name && d.name && name.toLowerCase() === d.name.toLowerCase()) {
        if (!rawVal || !d.measurementValue || rawVal.toLowerCase() === d.measurementValue.toLowerCase()) {
          return true;
        }
      }

      // 4. Same measurement value under same parent
      if (rawVal && d.measurementValue && rawVal.toLowerCase() === d.measurementValue.toLowerCase()) {
        return true;
      }

      return false;
    });

    if (matchIndex >= 0) {
      const target = drafts[matchIndex];
      if (id && (!target.id || target.id.startsWith('temp-') || target.id.startsWith('var-'))) {
        target.id = id;
      }
      if (preferCode && ('code' in v || 'sku' in v)) {
        target.code = code;
        target.sku = code;
      } else if (!target.code && code) {
        target.code = code;
        target.sku = code;
      }
      if (!target.name && name) target.name = name;
      if (!target.measurementValue && rawVal) target.measurementValue = rawVal;
      if (!target.uomId && uomId) target.uomId = uomId;
      if (target.openingStock === undefined && openingStock !== undefined) target.openingStock = openingStock;
      if (target.minStockLevel === undefined && minStockLevel !== undefined) target.minStockLevel = minStockLevel;
      if (target.reorderPoint === undefined && reorderPoint !== undefined) target.reorderPoint = reorderPoint;
      if (target.standardCost === undefined && standardCost !== undefined) target.standardCost = standardCost;
      if (!target.customFields && customFields) target.customFields = customFields;
    } else {
      drafts.push({
        id: id || undefined,
        code: code || undefined,
        sku: code || undefined,
        name: name || undefined,
        measurementValue: rawVal || undefined,
        uomId: uomId || undefined,
        openingStock,
        minStockLevel,
        reorderPoint,
        standardCost,
        customFields,
      });
    }
  };

  const specs = (material.specs || {}) as Record<string, any>;

  // 1. From specs.measurementVariants
  if (Array.isArray(specs.measurementVariants)) {
    for (const v of specs.measurementVariants) {
      addOrMergeDraft(v, true);
    }
  }

  // 2. From specs.variants
  if (Array.isArray(specs.variants)) {
    for (const v of specs.variants) {
      addOrMergeDraft(v, true);
    }
  }

  // 3. From (material as any).variants
  if (Array.isArray((material as any).variants)) {
    for (const v of (material as any).variants) {
      addOrMergeDraft(v);
    }
  }

  return drafts.map((v, idx) => {
    const rawVal = (v.measurementValue || '').trim();
    const storedName = (v.name || '').trim();
    const storedCode = (v.code || v.sku || '').trim();
    const vCode = isGeneratedVariantCode(material.code, storedCode) ? '' : storedCode;

    const isGenericVariantName = !storedName || /^variant\s*\d*$/i.test(storedName) || /^\d+$/.test(storedName);
    const displayName = getVariantLabel(material.name, isGenericVariantName ? '' : storedName, rawVal || `Variant ${idx + 1}`);

    const vId = v.id && !v.id.startsWith('temp-') && !v.id.startsWith('var-')
      ? v.id
      : `${material.id}__var__${vCode || idx + 1}`;

    const numOpeningStock = Number(v.openingStock) || 0;
    const numCost = Number(v.standardCost ?? material.standardCost ?? 0) || 0;
    const numMinStock = Number(v.minStockLevel ?? material.minStockLevel ?? 0) || 0;
    const numReorder = Number(v.reorderPoint ?? material.reorderPoint ?? 0) || 0;

    const variantMaterial: Material = {
      ...material,
      id: vId,
      code: vCode,
      name: displayName,
      description: material.description
        ? `${material.description}${rawVal ? ` · Specification: ${rawVal}` : ''}`
        : (rawVal ? `Variant measurement: ${rawVal}` : undefined),
      isVariant: true,
      parentMaterialId: material.id,
      parentMaterialName: material.name,
      parentCode: material.code,
      parentOptionId: material.id,
      parentItemName: material.name,
      measurementValue: rawVal || undefined,
      openingStock: numOpeningStock,
      standardCost: numCost,
      minStockLevel: numMinStock,
      reorderPoint: numReorder,
      uomId: v.uomId || material.uomId,
      uom: material.uom,
      category: material.category,
      categoryId: material.categoryId,
      productFamilyId: (material as any).productFamilyId || specs.productFamilyId || null,
      productFamily: (material as any).productFamily || null,
      materialType: material.materialType,
      status: material.status || 'ACTIVE',
      specs: {
        ...specs,
        isVariant: true,
        parentMaterialId: material.id,
        measurementValue: rawVal,
        openingStock: numOpeningStock,
        standardCost: numCost,
      },
    };
    return variantMaterial;
  });
}

export function expandMaterialsWithVariants(materials: Material[]): Material[] {
  const result: Material[] = [];
  const seenIds = new Set<string>();
  const parentIds = new Set(materials.filter((material) =>
    !material.isVariant && !(material.specs as any)?.isVariant && !material.parentMaterialId
  ).map((material) => material.id));

  for (const material of materials) {
    const parentId = material.parentMaterialId || (material.specs as any)?.parentMaterialId;
    // Material variants can exist both in the parent's specs and as standalone
    // material records. Only expand the set shown on the parent inventory item.
    if (parentId && parentIds.has(parentId)) continue;
    if (!seenIds.has(material.id)) {
      seenIds.add(material.id);
      result.push(material);
    }
    if (!material.isVariant && !(material.specs as any)?.isVariant) {
      const variants = extractMaterialVariants(material);
      for (const variant of variants) {
        if (!seenIds.has(variant.id)) {
          seenIds.add(variant.id);
          result.push(variant);
        }
      }
    }
  }
  return result;
}

