/**
 * Detects whether a SKU or code was entered by the user rather than auto-generated by the system.
 */
export function isCustomSku(skuOrCode?: string | null, metadataOrSpecs?: Record<string, unknown> | null): boolean {
  if (!skuOrCode || !skuOrCode.trim()) return false;
  const val = skuOrCode.trim();

  if (metadataOrSpecs) {
    if (metadataOrSpecs.hasCustomSku === false || metadataOrSpecs.hasCustomCode === false) {
      return false;
    }
    if (metadataOrSpecs.hasCustomSku === true || metadataOrSpecs.hasCustomCode === true) {
      return true;
    }
    if (typeof metadataOrSpecs.userSku === 'string') {
      return Boolean(metadataOrSpecs.userSku.trim());
    }
    if (typeof metadataOrSpecs.userCode === 'string') {
      return Boolean(metadataOrSpecs.userCode.trim());
    }
  }

  // System auto-generated fallback pattern: SKU-XXXX-XXXX, MAT-XXXX-XXXX, PROD-XXXX-XXXX
  const autoGenRegex = /^(SKU|MAT|PROD)-[0-9A-Z]{6,12}-[0-9A-Z]{2,8}$/i;
  if (autoGenRegex.test(val)) {
    return false;
  }

  return true;
}

