export function useVendors(status: LifecycleStatus = 'APPROVED') {
  return useQuery({
    queryKey: ['vendors', { status }],
    queryFn: () => apiClient.get<ListResponse<Vendor>>(`${MASTER_DATA}/vendors`, { status, limit: '1000' }),
  });
}

export function useProducts(
  status?: LifecycleStatus,
  page = 1,
  limit = 10,
  filters?: { productFamilyId?: string; categoryId?: string; search?: string; excludeVariants?: boolean; expandVariants?: boolean }
) {
  return useQuery({
    queryKey: ['products', { status, page, limit, ...filters }],
    refetchOnMount: 'always',
    staleTime: 0,
    queryFn: async () => {
      const params: Record<string, string> = {
        page: String(page),
        limit: String(limit),
      };
      if (status) params.status = status;
      if (filters?.productFamilyId) params.productFamilyId = filters.productFamilyId;
      if (filters?.categoryId) params.categoryId = filters.categoryId;
      if (filters?.search) params.search = filters.search;
      const res = await apiClient.get<ListResponse<Product>>(`${MASTER_DATA}/products`, params);
      if (!res || !Array.isArray(res.items)) return res;
      if (filters?.excludeVariants) return res;
      if (filters?.expandVariants === false) return res;

      const expandedItems = expandProductsWithVariants(res.items);
      return {
        ...res,
        items: expandedItems,
        total: expandedItems.length,
      };
    },
  });
}

export function useProduct(id: string) {
  const baseId = id && id.includes('__var__') ? id.split('__var__')[0] : id;
  return useQuery({
    queryKey: ['products', 'detail', baseId],
    enabled: Boolean(baseId),
    refetchOnMount: 'always',
    staleTime: 0,
    queryFn: () => apiClient.get<Product & { category?: Category; productFamily?: ProductFamily; uom?: Uom }>(`${MASTER_DATA}/products/${baseId}`),
  });
}

export function useMaterials(
  status?: LifecycleStatus,
  page = 1,
  limit = 10,
  filters?: { search?: string; categoryId?: string; materialType?: string; excludeVariants?: boolean; expandVariants?: boolean }
) {
  const params: Record<string, string> = {
    page: String(page),
    limit: String(limit),
  };
  if (status) params.status = status;
  if (filters?.search) params.search = filters.search;
  if (filters?.categoryId) params.categoryId = filters.categoryId;
  if (filters?.materialType) params.materialType = filters.materialType;

  return useQuery({
    queryKey: ['materials', { status, page, limit, filters }],
    refetchOnMount: 'always',
    staleTime: 0,
    queryFn: async () => {
      const res = await apiClient.get<ListResponse<Material>>(`${MASTER_DATA}/materials`, params);
      if (!res || !Array.isArray(res.items)) return res;
      if (filters?.excludeVariants) return res;
      if (filters?.expandVariants === false) return res;

      const expandedItems = expandMaterialsWithVariants(res.items);
      return {
        ...res,
        items: expandedItems,
        total: expandedItems.length,
      };
    },
  });
}

